"""Reporting for the username feature — and what it refuses to report.

The trips drawer shipped measurable by nothing: trips were counted, drives were
counted, and the one feature with a stated purpose had no number attached to
it. These tests pin both halves of the fix.

**What is counted.** Claims and releases are recorded by the server, so they
cannot be blocked or forged; adoption is read from the `trips` table, so an ad
blocker cannot move it; and "came back" needs a real gap, or two legs of one
holiday planned in one sitting would read as retention.

**What is not.** No username reaches `app_events`, no username reaches the
console, and no endpoint here can be drilled into a list of people. That is the
same rule `events.normalize_path` enforces on `/u/<name>`, and it would be
pointless there if this module gave the names back on another screen.
"""

